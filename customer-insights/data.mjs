import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { parseCsv } from "./model.mjs";
import { definitions, validateAndJoin } from "./contract.mjs";

export { definitions, validateAndJoin } from "./contract.mjs";

const defaultDirectory = fileURLToPath(new URL("../data/csv/", import.meta.url));

export async function loadSnapshot(directory = defaultDirectory) {
  const entries = await Promise.all(Object.entries(definitions).map(async ([name, definition]) =>
    [name, parseCsv(await readFile(join(directory, definition.file), "utf8"))]
  ));
  const tables = Object.fromEntries(entries);
  return {
    mode: "snapshot",
    loadedAt: new Date().toISOString(),
    disclosure: "Local POC snapshot. No live Fabric, D365, SharePoint or Databricks connection. Churn scores and actions are prepared demo values, not generated by this app.",
    sources: Object.entries(definitions).map(([name, d]) => ({ name, file: d.file, rows: tables[name].length })),
    accounts: validateAndJoin(tables)
  };
}
